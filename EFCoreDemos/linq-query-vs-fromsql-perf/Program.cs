using BenchmarkDotNet.Running;
using linq_query_vs_fromsql_perf.Benchmarks;
using linq_query_vs_fromsql_perf.Chinook;
using Microsoft.EntityFrameworkCore;

// Default: show the SQL each path sends and the top of the report.
// Benchmark:  dotnet run -c Release -- benchmark
if (args.Length > 0 && args[0].Equals("benchmark", StringComparison.OrdinalIgnoreCase))
{
    BenchmarkRunner.Run<AlbumSalesBenchmarks>(args: args[1..]);
    return;
}

var options = new DbContextOptionsBuilder<ChinookContext>()
    .UseSqlServer(AlbumSalesBenchmarks.ConnectionString)
    .Options;

await using var context = new ChinookContext(options);

var start = AlbumSalesBenchmarks.Start;
var end = AlbumSalesBenchmarks.End;
var minRevenue = AlbumSalesBenchmarks.MinRevenue;

var linqQuery = AlbumSalesQueries.Linq(context, start, end, minRevenue);
var fromSqlQuery = AlbumSalesQueries.FromSql(context, start, end, minRevenue);

Console.WriteLine($"Album sales report: {start:yyyy-MM-dd} to {end:yyyy-MM-dd}, revenue >= {minRevenue:C}");
Console.WriteLine();

Console.WriteLine("== LINQ (SQL generated by EF Core) ==");
Console.WriteLine(linqQuery.ToQueryString());
var linq = await linqQuery.ToListAsync();
Console.WriteLine($"-> {linq.Count} rows");
Console.WriteLine();

Console.WriteLine("== FromSql (hand-written SQL) ==");
Console.WriteLine(fromSqlQuery.ToQueryString());
var fromSql = await fromSqlQuery.ToListAsync();
Console.WriteLine($"-> {fromSql.Count} rows");
Console.WriteLine();

Console.WriteLine("Top 5 albums by revenue:");
Console.WriteLine($"  {"Album",-40} {"Invoices",8} {"Tracks",6} {"Units",5} {"Revenue",8}");
foreach (var row in fromSql.Take(5))
{
    var title = row.AlbumTitle.Length > 40 ? row.AlbumTitle[..37] + "..." : row.AlbumTitle;
    Console.WriteLine($"  {title,-40} {row.InvoiceCount,8} {row.DistinctTracksSold,6} {row.UnitsSold,5} {row.Revenue,8:C}");
}
Console.WriteLine();

var same = linq.Select(r => (r.AlbumId, r.UnitsSold, r.Revenue))
    .SequenceEqual(fromSql.Select(r => (r.AlbumId, r.UnitsSold, r.Revenue)));
Console.WriteLine(same ? "Both paths returned identical rows in the same order." : "WARNING: the two paths returned different rows.");
Console.WriteLine();
Console.WriteLine("Hint: run `dotnet run -c Release -- benchmark` to execute the BenchmarkDotNet harness.");
