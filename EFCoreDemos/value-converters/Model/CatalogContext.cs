using Microsoft.EntityFrameworkCore;

namespace value_converters.Model;

// Declared in "chart" order, deliberately NOT alphabetical: as text, Blues < Classical < Jazz < Metal < Rock.
public enum Genre
{
    Rock = 0,
    Jazz = 1,
    Metal = 2,
    Blues = 3,
    Classical = 4
}

public class Album
{
    public AlbumId Id { get; set; }
    public required string Title { get; set; }
    public List<Track> Tracks { get; set; } = [];
}

public class Track
{
    public TrackId Id { get; set; }
    public required string Name { get; set; }
    public Genre Genre { get; set; }
    public AlbumId AlbumId { get; set; }
    public Album? Album { get; set; }

    // Custom ValueConverter: the list is opaque JSON text as far as EF's query pipeline is concerned.
    public List<string> Tags { get; set; } = [];

    // No converter: an EF primitive collection. Also stored as JSON, but EF knows what's inside.
    public List<string> Moods { get; set; } = [];
}

public class Customer
{
    public int Id { get; set; }
    public required string Name { get; set; }

    // Encrypted at rest by EncryptedStringConverter.
    public required string Email { get; set; }
}

public class CatalogContext(DbContextOptions<CatalogContext> options) : DbContext(options)
{
    public DbSet<Album> Albums => Set<Album>();
    public DbSet<Track> Tracks => Set<Track>();
    public DbSet<Customer> Customers => Set<Customer>();

    public static DbContextOptions<CatalogContext> CreateOptions(string connectionString, Action<string>? log = null)
    {
        var builder = new DbContextOptionsBuilder<CatalogContext>().UseSqlite(connectionString);
        if (log != null)
        {
            builder.LogTo(log, [DbLoggerCategory.Database.Command.Name], Microsoft.Extensions.Logging.LogLevel.Information)
                .EnableSensitiveDataLogging();
        }

        return builder.Options;
    }

    // Model-wide: every TrackId / AlbumId property gets its converter without a per-property HasConversion.
    protected override void ConfigureConventions(ModelConfigurationBuilder configurationBuilder)
    {
        configurationBuilder.Properties<TrackId>().HaveConversion<TrackIdConverter>();
        configurationBuilder.Properties<AlbumId>().HaveConversion<AlbumIdConverter>();
    }

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        // Converted keys aren't generated by the database here; the seed assigns them.
        modelBuilder.Entity<Album>().Property(a => a.Id).ValueGeneratedNever();

        modelBuilder.Entity<Track>(entity =>
        {
            entity.Property(t => t.Id).ValueGeneratedNever();

            // Enum stored as its name ("Rock") instead of its number (0).
            entity.Property(t => t.Genre).HasConversion<string>().HasMaxLength(20);

            entity.Property(t => t.Tags).HasConversion(new JsonListConverter(), new StringListComparer());
        });

        modelBuilder.Entity<Customer>()
            .Property(c => c.Email)
            .HasConversion<EncryptedStringConverter>();
    }
}

public static class CatalogSeed
{
    public static void Seed(CatalogContext db)
    {
        var backInBlack = new Album { Id = new AlbumId(1), Title = "Back in Black" };
        var kindOfBlue = new Album { Id = new AlbumId(2), Title = "Kind of Blue" };
        var masterOfPuppets = new Album { Id = new AlbumId(3), Title = "Master of Puppets" };
        var fourSeasons = new Album { Id = new AlbumId(4), Title = "The Four Seasons" };
        var texasFlood = new Album { Id = new AlbumId(5), Title = "Texas Flood" };

        db.Albums.AddRange(backInBlack, kindOfBlue, masterOfPuppets, fourSeasons, texasFlood);

        db.Tracks.AddRange(
            new Track { Id = new TrackId(1), Name = "Hells Bells", Genre = Genre.Rock, Album = backInBlack, Tags = ["single", "remastered"], Moods = ["loud"] },
            new Track { Id = new TrackId(2), Name = "Back in Black", Genre = Genre.Rock, Album = backInBlack, Tags = ["single"], Moods = ["loud", "upbeat"] },
            new Track { Id = new TrackId(3), Name = "So What", Genre = Genre.Jazz, Album = kindOfBlue, Tags = ["modal"], Moods = ["calm"] },
            new Track { Id = new TrackId(4), Name = "Blue in Green", Genre = Genre.Jazz, Album = kindOfBlue, Tags = [], Moods = ["calm", "sad"] },
            new Track { Id = new TrackId(5), Name = "Master of Puppets", Genre = Genre.Metal, Album = masterOfPuppets, Tags = ["live"], Moods = ["loud"] },
            new Track { Id = new TrackId(6), Name = "Spring", Genre = Genre.Classical, Album = fourSeasons, Tags = [], Moods = ["upbeat"] },
            new Track { Id = new TrackId(7), Name = "Pride and Joy", Genre = Genre.Blues, Album = texasFlood, Tags = ["single"], Moods = ["upbeat"] });

        db.Customers.AddRange(
            new Customer { Name = "Ada", Email = "ada@example.com" },
            new Customer { Name = "Alan", Email = "alan@example.com" },
            new Customer { Name = "Grace", Email = "grace@example.org" });

        db.SaveChanges();
    }
}
